import os
import sys
import pandas as pd
import numpy as np

# Add backend to sys.path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')

from app.reports.pdf_generator import generate_executive_pdf_report
from app.reports.analysis_engine import analyze_dataset_for_report

def main():
    print("Testing PDF Generation with realistic dataset...")
    # Create sample dataframe with multiple data types
    np.random.seed(42)
    n = 150
    df = pd.DataFrame({
        "Transaction_ID": [f"TXN_{i:04d}" for i in range(1, n + 1)],
        "Date": pd.date_range(start="2026-01-01", periods=n, freq="D"),
        "Region": np.random.choice(["North America", "Europe", "Asia-Pacific", "Latin America"], size=n, p=[0.4, 0.3, 0.2, 0.1]),
        "Category": np.random.choice(["Electronics", "Home & Kitchen", "Apparel", "Office Supplies"], size=n),
        "Sales_Amount": np.random.exponential(scale=500, size=n) + 50,
        "Profit_Margin": np.random.normal(loc=0.22, scale=0.08, size=n),
        "Units_Sold": np.random.randint(1, 20, size=n),
        "Customer_Rating": np.random.choice([1, 2, 3, 4, 5, np.nan], size=n, p=[0.05, 0.05, 0.15, 0.45, 0.25, 0.05])
    })

    # Add a few duplicate rows and outliers for comprehensive testing
    df.loc[148] = df.loc[0].copy()
    df.loc[149] = df.loc[1].copy()
    df.loc[10, "Sales_Amount"] = 4500.0  # extreme outlier

    print(f"Dataset shape: {df.shape}")
    print(f"Columns: {list(df.columns)}")

    # 1. Analyze dataset
    analysis = analyze_dataset_for_report(
        df=df,
        dataset_name="Quarterly_Sales_Performance.csv",
        project_name="Commercial Analytics",
        version_num=1
    )
    print("Analysis completed successfully.")
    print(f"Data Quality Score: {analysis['data_quality']['overall_score']}/100")
    print(f"Key findings count: {len(analysis['key_findings'])}")

    # 2. Generate PDF
    pdf_bytes = generate_executive_pdf_report(
        dataset_name="Quarterly_Sales_Performance.csv",
        row_count=len(df),
        col_count=len(df.columns),
        df=df,
        analysis=analysis,
        project_name="Commercial Analytics",
        version_num=1
    )

    print(f"Generated PDF size: {len(pdf_bytes):,} bytes")
    assert pdf_bytes.startswith(b"%PDF"), "Generated bytes do not start with %PDF header"

    output_path = os.path.join(os.path.dirname(__file__), "test_generated_report.pdf")
    with open(output_path, "wb") as f:
        f.write(pdf_bytes)
    print(f"Saved test PDF to: {output_path}")

    # Check for forbidden branding words in PDF raw stream / text if any
    forbidden = [b"Aether Copilot", b"Analytical Copilot", b"AI Copilot"]
    for word in forbidden:
        if word in pdf_bytes:
            print(f"WARNING: Found forbidden term '{word.decode()}' in PDF!")
        else:
            print(f"Verified: No forbidden term '{word.decode()}' in PDF.")

    print("\n[SUCCESS] PDF Generation and Verification test PASSED perfectly!")

if __name__ == "__main__":
    main()
